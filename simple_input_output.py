# Task: Evaluate the results of four basic arithmetic operations
# (addition, subtraction, multiplication, division) using two
# float values entered by the user.

a = float(input("Enter value for a: "))
b = float(input("Enter value for b: "))

print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)

print("\nThat's all, folks!")
